-- ==========================================
-- 회원 테이블
-- ==========================================
CREATE TABLE users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id VARCHAR2(30) UNIQUE NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    nickname VARCHAR2(30) UNIQUE NOT NULL,
    email VARCHAR2(255) UNIQUE NOT NULL,
    role VARCHAR2(10) DEFAULT 'USER' NOT NULL,
    status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 회원 권한
ALTER TABLE users
ADD CONSTRAINT chk_users_role
CHECK (role IN ('USER', 'ADMIN'));

-- 회원 상태
ALTER TABLE users
ADD CONSTRAINT chk_users_status
CHECK (status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN'));

-- ==========================================
-- 로그인 로그 테이블
-- ==========================================
CREATE TABLE login_logs (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    ip_address VARCHAR2(45) NOT NULL,
    user_agent VARCHAR2(255),
    status VARCHAR2(20) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT fk_login_logs_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE
);

-- 로그인 로그 인덱스
CREATE INDEX idx_login_logs_user_created
ON login_logs (user_id, created_at);

CREATE INDEX idx_login_logs_ip_created
ON login_logs (ip_address, created_at);

-- ==========================================
-- 관리자 활동 로그 테이블
-- ==========================================
CREATE TABLE admin_action_logs (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id NUMBER NOT NULL,
    action_type VARCHAR2(50) NOT NULL,
    target_type VARCHAR2(30) NOT NULL,
    target_id NUMBER NOT NULL,
    reason VARCHAR2(255),
    ip_address VARCHAR2(45) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT fk_admin_action_logs_admin
        FOREIGN KEY (admin_id)
        REFERENCES users(user_id)
);

-- 관리자 활동 로그 인덱스
CREATE INDEX idx_admin_logs_admin_created
ON admin_action_logs (admin_id, created_at);

CREATE INDEX idx_admin_logs_target
ON admin_action_logs (target_type, target_id);

-- ==========================================
-- 신고 테이블
-- ==========================================
CREATE TABLE reports (
    report_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id NUMBER NOT NULL,
    target_type VARCHAR2(20) NOT NULL,
    target_id NUMBER NOT NULL,
    reason VARCHAR2(255) NOT NULL,
    status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    resolved_by NUMBER,
    resolved_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT fk_reports_reporter
        FOREIGN KEY (reporter_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_reports_resolver
        FOREIGN KEY (resolved_by)
        REFERENCES users(user_id)
);

-- 신고 대상 유형
ALTER TABLE reports
ADD CONSTRAINT chk_reports_target_type
CHECK (target_type IN ('POST', 'COMMENT', 'USER'));

-- 신고 처리 상태
ALTER TABLE reports
ADD CONSTRAINT chk_reports_status
CHECK (status IN ('PENDING', 'REVIEWED', 'RESOLVED', 'REJECTED'));

-- 신고 인덱스
CREATE INDEX idx_reports_target
ON reports (target_type, target_id);

CREATE INDEX idx_reports_status_created
ON reports (status, created_at);

-- ==========================================
-- 영화 테이블
-- =========================================
CREATE TABLE movies (
    movie_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id NUMBER UNIQUE NOT NULL,
    title VARCHAR2(255) NOT NULL,
    original_title VARCHAR2(255),
    overview CLOB,
    runtime NUMBER,
    release_date DATE,
    poster_path VARCHAR2(255),
    backdrop_path VARCHAR2(255),
    vote_average NUMBER(3,1) DEFAULT 0.0 NOT NULL,
    vote_count NUMBER DEFAULT 0 NOT NULL,
    popularity NUMBER(10,3) DEFAULT 0.0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 영화 인덱스
CREATE INDEX idx_movies_title
ON movies (title);

CREATE INDEX idx_movies_release_date
ON movies (release_date);

CREATE INDEX idx_movies_popularity
ON movies (popularity);

