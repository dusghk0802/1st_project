-- ==========================================
-- 게시판 테이블
-- ==========================================
CREATE TABLE boards (
    board_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(50) UNIQUE NOT NULL,
    description VARCHAR2(255),
    sort_order NUMBER DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ==========================================
-- 게시판 카테고리 테이블
-- ==========================================
CREATE TABLE categories (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id NUMBER NOT NULL,
    name VARCHAR2(50) NOT NULL,
    sort_order NUMBER DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT uq_categories_board_name
        UNIQUE (board_id, name),

    CONSTRAINT fk_categories_board
        FOREIGN KEY (board_id)
        REFERENCES boards(board_id)
        ON DELETE CASCADE
);

DESC categories;
-- ==========================================
-- 게시글 테이블
-- ==========================================
CREATE TABLE posts (
    post_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id NUMBER NOT NULL,
    category_id NUMBER,
    author_id NUMBER NOT NULL,
    movie_id NUMBER,
    title VARCHAR2(200) NOT NULL,
    content CLOB NOT NULL,
    view_count NUMBER DEFAULT 0 NOT NULL,
    like_count NUMBER DEFAULT 0 NOT NULL,
    comment_count NUMBER DEFAULT 0 NOT NULL,
    status VARCHAR2(20) DEFAULT 'PUBLISHED' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT fk_posts_board
        FOREIGN KEY (board_id)
        REFERENCES boards(board_id),

    CONSTRAINT fk_posts_category
        FOREIGN KEY (category_id)
        REFERENCES categories(category_id)
        ON DELETE SET NULL,

    CONSTRAINT fk_posts_author
        FOREIGN KEY (author_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_posts_movie
        FOREIGN KEY (movie_id)
        REFERENCES movies(movie_id)
        ON DELETE SET NULL
);

-- 게시글 상태
ALTER TABLE posts
ADD CONSTRAINT chk_posts_status
CHECK (status IN ('PUBLISHED', 'HIDDEN', 'DELETED'));

-- 게시글 인덱스
CREATE INDEX idx_posts_board_created
ON posts (board_id, created_at);

CREATE INDEX idx_posts_author_created
ON posts (author_id, created_at);

CREATE INDEX idx_posts_category_created
ON posts (category_id, created_at);

CREATE INDEX idx_posts_movie_created
ON posts (movie_id, created_at);

